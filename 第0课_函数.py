# ==========================================================
# 四、参数可以有默认值
# ==========================================================

def bandpass_info(low=1, high=45):
    print(f"滤波范围: {low} - {high} Hz")

bandpass_info()           # 用默认值 -> 1 - 45 Hz
bandpass_info(8, 13)      # 自己指定 -> 8 - 13 Hz
bandpass_info(high=30)    # 只改一个 -> 1 - 30 Hz

# 这个用法你以后天天见，比如 mne 里：
#     raw.filter(l_freq=1, h_freq=45)
# 括号里那些 l_freq=、h_freq= 就是函数的参数名。


# ==========================================================
# 五、函数可以调用函数
# ==========================================================

def average(nums):
    """算一个列表的平均值。"""
    return sum(nums) / len(nums)

def report(nums):
    """打印这个列表的平均值。"""
    avg = average(nums)        # 调用上面那个函数
    print(f"数据: {nums}")
    print(f"平均值: {avg:.2f}")

report([1, 2, 3, 4, 5])
print()

# 这样拆开的好处：
#   average 只负责算，report 只负责显示。
#   以后你想在别的地方算平均值，直接调用 average 就行，不用重写。
#
# 专业说法叫"单一职责" —— 一个函数只干一件事。
# 你的脑电项目就会这样拆：
#   load_data()  只负责读数据
#   preprocess() 只负责滤波去伪迹
#   extract()    只负责提特征
#   train()      只负责训练分类器
# 每个都是一个小函数，在 main 里串起来。


