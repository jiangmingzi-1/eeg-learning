# ==========================================================
# 一、函数是什么，为什么要用它
# ==========================================================
#
# 现在假设你要算 3 个数的平均值，你可能会这么写：
#
#     a = (1 + 2 + 3) / 3
#     b = (10 + 20 + 30) / 3
#     c = (5 + 5 + 5) / 3
#
# 能跑，但有个问题：**"算平均值"这件事你写了 3 遍。**
#
# 如果以后你发现平均值的算法要改（比如去掉最大值再平均），
# 你得改 3 个地方。100 处用到就得改 100 处 —— 这就是 bug 的来源。
#
# 函数就是把"一件事"打包起来，给它起个名字，以后叫名字就行：
#
#     def average(x, y, z):
#         return (x + y + z) / 3
#
#     a = average(1, 2, 3)
#     b = average(10, 20, 30)
#     c = average(5, 5, 5)
#
# 好处：**改算法只改 1 个地方。**
#
# 为什么现在必须学它？
#   因为 mne（脑电库）的每个功能都是函数。
#   你以后写的每一行代码，都会长这样：
#
#     raw = mne.io.read_raw_edf("data.edf")     # 读数据是个函数
#     raw.filter(1, 45)                          # 滤波是个函数
#     psd = raw.compute_psd()                    # 算功率谱是个函数
#
#   看不懂函数，就看不懂 mne 的任何一行文档。


# ==========================================================
# 二、语法：def 三件套
# ==========================================================
#
# 一个函数由三部分组成：
#
#     def 函数名(参数):
#         要做的事
#         return 结果
#
#   def      —— 告诉 Python "我要定义一个函数"
#   函数名    —— 你给它起的名字，以后靠这个名字叫它
#   参数      —— 括号里的东西，是"喂给它的原料"
#   return   —— 把结果吐出来


# ---------- 例 1：最简单，没有参数，没有返回值 ----------

def say_hello():
    print("你好，我是脑电学习者")

say_hello()      # 调用它（必须有括号！）
say_hello()      # 可以调用很多次

# 注意：定义函数的时候，函数里的代码**不会执行**。
#       只有"调用"（写 say_hello()）的时候才会执行。


# ---------- 例 2：有参数 ----------

def greet(name):
    print("你好，" + name)

greet("小明")
greet("脑电")

# name 叫"参数"，"小明"叫"实参"。
# 每次调用，name 就被换成你传进来的那个值。


# ---------- 例 3：有返回值 —— 这是重点 ----------

def add(a, b):
    return a + b

result = add(3, 5)
print("add(3, 5) 的结果:", result)
print("结果还可以继续运算:", add(3, 5) * 2)

# return 的意思是"把结果交出来，交给调用者"。
# 有了 return，函数的结果才能被存进变量、继续参与运算。


# ==========================================================
# 三、最容易搞混的：return 和 print 的区别  ⭐
# ==========================================================

def add_with_return(a, b):
    return a + b

def add_with_print(a, b):
    print(a + b)

x = add_with_return(3, 5)
y = add_with_print(3, 5)

print()
print("有 return 的函数，结果存进 x 后是:", x)
print("只有 print 的函数，结果存进 y 后是:", y)
print()

# 看输出：y 是 None！
#
# 为什么？
#   print 只是"显示给你看"，显示完就没了，函数没有交出任何东西。
#   return 是"把结果交出来"，调用者才能接住它。
#
# 记牢这一句：
#     print 是给人看的，return 是给程序用的。
#
# 这个坑 extremely 常见。以后你写函数明明 print 出来是对的，
# 但存进变量就是 None —— 99% 是这里忘了写 return。

